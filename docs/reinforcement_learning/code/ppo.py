# DeBERTa is small enough to run on CPU if no GPU is available
rm_device = DEVICE
rm_tok = AutoTokenizer.from_pretrained(RM_ID)
rm_model = AutoModelForSequenceClassification.from_pretrained(RM_ID).to(rm_device)
rm_model.eval()


@torch.no_grad()
def reward_score(prompt: str, response: str) -> float:
    """
    Score a single prompt-response pair with the pre-built reward model.

    The DeBERTa model expects the concatenation format:
        "Question: <prompt>\n\nAnswer: <response>"
    and returns a single scalar logit (higher is better).
    """
    text = f"Question: {prompt}\n\nAnswer: {response}"
    enc  = rm_tok(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=MAXLEN_RM,
    ).to(rm_device)
    return float(rm_model(**enc).logits[0])

class WrappedRewardModel(torch.nn.Module):
    def __init__(self, policy_tok, rm_tok, rm_model, device):
        super().__init__()
        self.policy_tok = policy_tok
        self.rm_tok     = rm_tok
        self.rm         = rm_model
        self.device     = device
        self.config            = rm_model.config
        self.base_model_prefix = rm_model.base_model_prefix

    def forward(self, input_ids, attention_mask=None, **kwargs):
        # Decode on CPU regardless of where input_ids lives
        texts = self.policy_tok.batch_decode(
            input_ids.cpu(), skip_special_tokens=True
        )
        scores = []
        for text in texts:
            enc = self.rm_tok(
                text,
                return_tensors="pt",
                truncation=True,
                max_length=MAXLEN_RM,
                padding=True,
            ).to(self.device)          # explicitly send to rm's device
            with torch.no_grad():
                score = self.rm(**enc).logits[0, 0]
            scores.append(score.to(input_ids.device))  # return on same device as input
        return torch.stack(scores)

    def __getattr__(self, name):
        try:
            return super().__getattr__(name)
        except AttributeError:
            return getattr(self.rm, name)

