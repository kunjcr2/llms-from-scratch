# Load the SFT checkpoint with a value head attached (required for PPO)
base = AutoModelForCausalLM.from_pretrained(BASE_ID, device_map="auto")
policy = PeftModel.from_pretrained(base, "ckpt_sft").merge_and_unload()
ref_policy = create_reference_model(policy)
value_model = AutoModelForSequenceClassification.from_pretrained(
    BASE_ID, num_labels=1, device_map="auto"
)

ppo_cfg = PPOConfig(
    learning_rate=1e-5,
    batch_size=16,
    mini_batch_size=8,
    num_train_epochs=2,
    whiten_rewards=True,
    remove_unused_columns=False,
    gradient_checkpointing=False,  # ← prevents the wrapper attr error
)


# ── Build a HF Dataset of chat-formatted prompts ──────────────────────────────
raw_prompts = load_dataset("HuggingFaceH4/ultrachat_200k", split="train_sft[:100]")["prompt"]

ppo_dataset = Dataset.from_list([
    {"input_ids": tok.apply_chat_template(
        [{"role": "user", "content": p}],
        tokenize=True,
        add_generation_prompt=True,
        return_dict=False
    )}
    for p in raw_prompts
])
wrapped_rm = WrappedRewardModel(tok, rm_tok, rm_model, rm_device)

ppo_tr = PPOTrainer(
    args=ppo_cfg,
    processing_class=tok,
    model=policy,
    ref_model=ref_policy,
    reward_model=wrapped_rm,
    value_model=value_model,
    train_dataset=ppo_dataset
)

ppo_tr.train() # requires JUST input ids

# ── Save final aligned policy ─────────────────────────────────────────────────
ppo_tr.model.save_pretrained("ckpt_ppo")
tok.save_pretrained("ckpt_ppo")
print("Saved aligned policy → ckpt_ppo")

